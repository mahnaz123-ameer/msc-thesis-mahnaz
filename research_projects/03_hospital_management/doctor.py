def add_doctor(doctors, doctor_id, name, specialization, degree, experience_years, consultation_fee):
    """Add a doctor to the system."""
    if doctor_id in doctors:
        return False, "Doctor ID already exists"
    if experience_years < 0:
        return False, "Invalid experience"
    if consultation_fee <= 0:
        return False, "Invalid consultation fee"
    doctors[doctor_id] = {
        "name": name, "specialization": specialization,
        "degree": degree, "experience_years": experience_years,
        "consultation_fee": consultation_fee, "active": True,
        "rating": [], "patients_seen": 0,
    }
    return True, "Doctor added"


def remove_doctor(doctors, doctor_id):
    """Remove a doctor."""
    if doctor_id not in doctors:
        return False, "Doctor not found"
    del doctors[doctor_id]
    return True, "Doctor removed"


def update_consultation_fee(doctors, doctor_id, new_fee):
    """Update doctor consultation fee."""
    if doctor_id not in doctors:
        return False, "Doctor not found"
    if new_fee <= 0:
        return False, "Fee must be positive"
    doctors[doctor_id]["consultation_fee"] = new_fee
    return True, "Fee updated"


def add_rating(doctors, doctor_id, rating):
    """Add patient rating for a doctor."""
    if doctor_id not in doctors:
        return False, "Doctor not found"
    if rating < 1 or rating > 5:
        return False, "Rating must be between 1 and 5"
    doctors[doctor_id]["rating"].append(rating)
    return True, "Rating added"


def get_average_rating(doctors, doctor_id):
    """Get average patient rating for a doctor."""
    if doctor_id not in doctors:
        return None
    ratings = doctors[doctor_id]["rating"]
    if not ratings:
        return 0.0
    return round(sum(ratings) / len(ratings), 2)


def get_doctors_by_specialization(doctors, specialization):
    """Get all doctors with a specific specialization."""
    return {did: info for did, info in doctors.items()
            if info["specialization"].lower() == specialization.lower() and info["active"]}


def get_top_rated_doctors(doctors, top_n=5):
    """Get top N doctors by average rating."""
    rated = [(did, get_average_rating(doctors, did)) for did in doctors]
    sorted_docs = sorted(rated, key=lambda x: x[1] or 0, reverse=True)
    return sorted_docs[:top_n]


def calculate_doctor_revenue(doctors, doctor_id, patients_seen):
    """Calculate revenue generated by a doctor."""
    if doctor_id not in doctors:
        return None
    return doctors[doctor_id]["consultation_fee"] * patients_seen


def increment_patients_seen(doctors, doctor_id):
    """Increment the count of patients seen by doctor."""
    if doctor_id not in doctors:
        return False, "Doctor not found"
    doctors[doctor_id]["patients_seen"] += 1
    return True, "Patient count updated"


def deactivate_doctor(doctors, doctor_id):
    """Deactivate a doctor (e.g. on leave)."""
    if doctor_id not in doctors:
        return False, "Doctor not found"
    doctors[doctor_id]["active"] = False
    return True, "Doctor deactivated"


def reactivate_doctor(doctors, doctor_id):
    """Reactivate a doctor."""
    if doctor_id not in doctors:
        return False, "Doctor not found"
    doctors[doctor_id]["active"] = True
    return True, "Doctor reactivated"


def is_doctor_active(doctors, doctor_id):
    """Check if doctor is currently active."""
    if doctor_id not in doctors:
        return False
    return doctors[doctor_id]["active"]


def get_all_active_doctors(doctors):
    """Get all currently active doctors."""
    return {did: info for did, info in doctors.items() if info["active"]}


def calculate_experience_level(experience_years):
    """Classify doctor experience level."""
    if experience_years < 0:
        return None
    if experience_years < 3:
        return "Junior"
    elif experience_years < 8:
        return "Mid-level"
    elif experience_years < 15:
        return "Senior"
    else:
        return "Expert"


def search_doctor_by_name(doctors, keyword):
    """Search doctors by name."""
    keyword = keyword.lower()
    return {did: info for did, info in doctors.items()
            if keyword in info["name"].lower()}


def get_doctor_profile(doctors, doctor_id):
    """Get complete doctor profile."""
    if doctor_id not in doctors:
        return None
    doc = doctors[doctor_id].copy()
    doc["average_rating"] = get_average_rating(doctors, doctor_id)
    doc["experience_level"] = calculate_experience_level(doc["experience_years"])
    return doc


def calculate_department_revenue(doctors, specialization, avg_patients_per_day, working_days):
    """Calculate monthly revenue for a department."""
    dept_doctors = get_doctors_by_specialization(doctors, specialization)
    total = 0
    for did, info in dept_doctors.items():
        total += info["consultation_fee"] * avg_patients_per_day * working_days
    return round(total, 2)
